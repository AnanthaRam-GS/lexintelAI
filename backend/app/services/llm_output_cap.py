"""A per-request output-token cap for the answer provider (step 26b, brief mode).

The answer is generated by the frozen ``legal_answer_generation.generate_legal_answer``, which calls
``adapter.generate_structured_answer(prompt, schema=..., mode=...)`` and cannot pass a per-request limit. The brief route
sets the cap here for the duration of its pipeline run; the Groq adapter reads it for ``max_completion_tokens`` (and
for its pacing estimate), and the request-size guard reserves the same number. Outside a brief run nothing is set and
``LEGALAI_LLM_MAX_OUTPUT_TOKENS`` applies, unchanged.
"""

from __future__ import annotations

from contextlib import contextmanager
from contextvars import ContextVar
from typing import Iterator

_CAP: ContextVar[int | None] = ContextVar("legalai_output_token_cap", default=None)


def effective_max_output_tokens(default: int) -> int:
    cap = _CAP.get()
    return cap if cap else default


@contextmanager
def output_token_cap(tokens: int | None) -> Iterator[None]:
    marker = _CAP.set(tokens)
    try:
        yield
    finally:
        _CAP.reset(marker)
